#ifndef __LED_H
#define __LED_H

/* =====================================================================
 * LED 模块 —— 对外提供的函数声明
 * ---------------------------------------------------------------------
 * 头文件（.h）里只放"声明"，告诉别人"本模块能做什么"；
 * 具体怎么实现放在同名的 .c 文件里。
 * 其它文件只要 #include "LED.h"，就能用下面这些函数，
 * 不必知道 LED 到底接在哪个引脚上。
 * ===================================================================== */

void LED_Init(void);		//初始化 LED 用到的引脚（配成推挽输出）

void LED1_ON(void);			//点亮 LED1
void LED1_OFF(void);		//熄灭 LED1
void LED1_Turn(void);		//翻转 LED1（亮的变灭、灭的变亮）

void LED2_ON(void);			//点亮 LED2
void LED2_OFF(void);		//熄灭 LED2
void LED2_Turn(void);		//翻转 LED2

#endif
