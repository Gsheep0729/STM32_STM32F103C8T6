#ifndef __BUZZER_H
#define __BUZZER_H

/* =====================================================================
 * 蜂鸣器模块 —— 对外接口（头文件）
 * ---------------------------------------------------------------------
 * 其它文件只要 #include "Buzzer.h"，就能调用下面这几个函数，
 * 不需要知道蜂鸣器接在哪个引脚、是低电平还是高电平触发。
 * 具体实现见同目录的 Buzzer.c。
 * ===================================================================== */

void Buzzer_Init(void);		//蜂鸣器初始化：配好引脚，默认不响
void Buzzer_ON(void);		//蜂鸣器开启（响）
void Buzzer_OFF(void);		//蜂鸣器关闭（停）
void Buzzer_Turn(void);		//蜂鸣器状态翻转：响的变停、停的变响

#endif
